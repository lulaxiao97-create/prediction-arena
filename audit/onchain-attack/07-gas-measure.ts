import { ethers } from "ethers";
import { readFileSync } from "node:fs";
const abi = JSON.parse(readFileSync("artifacts/contracts/PredictionArena.sol/PredictionArena.json","utf8")).abi;
const p = new ethers.JsonRpcProvider("http://127.0.0.1:8546");
const USDC="0x833589fCD6eDb6E08f4c7C32D4f71b54bdA02913", ARENA="0x36f1bFbE3E0d0FA0941C031be278149D33f65684";
const OWNER="0x436b9d5e6fBd40eC93E881263bE53e59F8755Ba1";
const abiU=["function approve(address,uint256) returns (bool)","function balanceOf(address) view returns (uint256)"];
const slot=(a:string)=>ethers.keccak256(ethers.AbiCoder.defaultAbiCoder().encode(["address","uint256"],[a,9]));
const u=(x:string)=>ethers.parseUnits(x,6);
(async()=>{
  await p.send("anvil_impersonateAccount",[OWNER]);
  await p.send("anvil_setBalance",[OWNER,ethers.toBeHex(ethers.parseEther("10"))]);
  const owner=await p.getSigner(OWNER); const usr=await p.getSigner(3); const ua=await usr.getAddress();
  await p.send("anvil_setStorageAt",[USDC,slot(OWNER),ethers.toBeHex(u("100000"),32)]);
  await p.send("anvil_setStorageAt",[USDC,slot(ua),ethers.toBeHex(u("100000"),32)]);
  await (await new ethers.Contract(USDC,abiU,owner).approve(ARENA,ethers.MaxUint256)).wait();
  await (await new ethers.Contract(USDC,abiU,usr).approve(ARENA,ethers.MaxUint256)).wait();
  const A=new ethers.Contract(ARENA,abi,owner), U=new ethers.Contract(ARENA,abi,usr);
  const now=BigInt((await p.getBlock("latest"))!.timestamp);
  await (await A.createPool(400,"gas","t",now+600n)).wait();
  await (await A.seedPool(400,0,u("22.5"))).wait();
  await (await A.seedPool(400,1,u("22.5"))).wait();
  const r=await (await U.bet(400,0,u("50"),ethers.ZeroAddress)).wait();
  console.log("bet gasUsed",r.gasUsed.toString());
  const r2=await (await A.seedPool(400,0,u("10"))).wait();
  console.log("seedPool gasUsed",r2.gasUsed.toString());
  await p.send("evm_increaseTime",[700]); await p.send("evm_mine",[]);
  const r3=await (await A.settle(400,0,ethers.id("e"))).wait();
  console.log("settle gasUsed",r3.gasUsed.toString());
})();
