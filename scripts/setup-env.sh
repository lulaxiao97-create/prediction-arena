#!/usr/bin/env bash
# ─────────────────────────────────────────────────────────────────────────────
# Interactive .env builder — keeps the private key out of shell history and chat.
#
#   bash scripts/setup-env.sh
#
# • private key is read silently (read -s), validated, and its address shown back to you
# • writes .env with chmod 600, preserving the documented template
# ─────────────────────────────────────────────────────────────────────────────
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"
export PATH="$HOME/.bun/bin:/usr/local/bin:/usr/bin:/bin:$PATH"

ENV_FILE="${ENV_FILE:-$ROOT/.env}"

# Pre-fill from the existing .env so the only thing you must type is the key.
PREV_RPC=""; PREV_FEE=""; PREV_SAFE=""; PREV_BASESCAN=""
if [[ -f "$ENV_FILE" ]]; then
  PREV_RPC="$(grep -E '^BASE_RPC_URL=' "$ENV_FILE" | head -1 | cut -d= -f2- || true)"
  PREV_FEE="$(grep -E '^FEE_RECEIVER=' "$ENV_FILE" | head -1 | cut -d= -f2- || true)"
  PREV_SAFE="$(grep -E '^SAFE_ADDRESS=' "$ENV_FILE" | head -1 | cut -d= -f2- || true)"
  PREV_BASESCAN="$(grep -E '^BASESCAN_API_KEY=' "$ENV_FILE" | head -1 | cut -d= -f2- || true)"
  [[ "$PREV_FEE" =~ ^0x0+$ ]] && PREV_FEE=""
fi
NODE_BIN="$(command -v node || true)"
if [[ -z "$NODE_BIN" ]]; then
  echo "node not found — install Node 22+ first" >&2
  exit 1
fi

derive_address() {
  "$NODE_BIN" -e '
    const { Wallet } = require(process.argv[1] + "/node_modules/ethers");
    try { process.stdout.write(new Wallet(process.argv[2]).address); }
    catch (e) { process.exit(1); }
  ' "$ROOT" "$1"
}

echo "── Prediction Arena · .env setup ─────────────────────────────"
echo "Target file: $ENV_FILE"
echo

read -r -p "BASE_RPC_URL [${PREV_RPC:-https://mainnet.base.org}]: " RPC
RPC="${RPC:-${PREV_RPC:-https://mainnet.base.org}}"

while true; do
  read -r -s -p "PRIVATE_KEY (hidden, 0x + 64 hex): " KEY
  echo
  KEY="$(printf '%s' "$KEY" | tr -d '[:space:]')"
  if [[ ! "$KEY" =~ ^0x[0-9a-fA-F]{64}$ ]] || [[ "$KEY" =~ ^0x0+$ ]]; then
    echo "  ✗ malformed key (need 0x + 64 hex chars, not all zeros)"
    continue
  fi
  if ADDRESS="$(derive_address "$KEY")"; then
    echo "  ✓ deployer address: $ADDRESS"
    read -r -p "  is this the wallet you want to deploy from? [y/N]: " OK
    [[ "$OK" =~ ^[yY]$ ]] && break
  else
    echo "  ✗ key does not derive a valid account"
  fi
done

while true; do
  read -r -p "FEE_RECEIVER [${PREV_FEE:-required}]: " FEE
  FEE="$(printf '%s' "${FEE:-$PREV_FEE}" | tr -d '[:space:]')"
  if [[ "$FEE" =~ ^0x[0-9a-fA-F]{40}$ ]] && [[ ! "$FEE" =~ ^0x0+$ ]]; then
    if [[ "${FEE,,}" == "${ADDRESS,,}" ]]; then
      echo "  ⚠ fee receiver == deployer. Fine for a dry run, risky in production."
    fi
    break
  fi
  echo "  ✗ not a valid address"
done

read -r -p "SAFE_ADDRESS [${PREV_SAFE:-optional, Enter to skip}]: " SAFE
SAFE="$(printf '%s' "${SAFE:-$PREV_SAFE}" | tr -d '[:space:]')"
if [[ -n "$SAFE" && ! "$SAFE" =~ ^0x[0-9a-fA-F]{40}$ ]]; then
  echo "  ✗ invalid SAFE_ADDRESS" >&2
  exit 1
fi

read -r -s -p "BASESCAN_API_KEY [${PREV_BASESCAN:+keep existing}${PREV_BASESCAN:-optional, Enter to skip}]: " BASESCAN
echo
BASESCAN="$(printf '%s' "${BASESCAN:-$PREV_BASESCAN}" | tr -d '[:space:]')"

umask 077
{
  echo "# generated by scripts/setup-env.sh on $(date -Is)"
  echo "PRIVATE_KEY=$KEY"
  echo "FEE_RECEIVER=$FEE"
  echo "BASE_RPC_URL=$RPC"
  [[ -n "$SAFE" ]] && echo "SAFE_ADDRESS=$SAFE"
  [[ -n "$BASESCAN" ]] && echo "BASESCAN_API_KEY=$BASESCAN"
  echo "# optional"
  echo "USDC_ADDRESS=0x833589fCD6eDb6E08f4c7C32D4f71b54bdA02913"
  echo "CHAIN_ID=8453"
} > "$ENV_FILE"
chmod 600 "$ENV_FILE"

echo
echo "✓ wrote $ENV_FILE (chmod 600)"
echo "  deployer : $ADDRESS"
echo "  feeVault : $FEE"
[[ -n "$SAFE" ]] && echo "  safe     : $SAFE"
echo
echo "Next: bash scripts/go-mainnet.sh"
