/**
 * docs/WHITEPAPER.md is the canonical whitepaper; this exports it into the app as a string so the
 * /whitepaper route renders the *same* text GitHub shows. Two copies would drift within a week.
 *
 *   bun scripts/export-whitepaper.ts
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { join } from "node:path";

const ROOT = join(import.meta.dir, "..");
const SRC = join(ROOT, "docs", "WHITEPAPER.md");
const OUT = join(ROOT, "frontend", "src", "content", "whitepaper.ts");
const PUBLIC = join(ROOT, "frontend", "public", "WHITEPAPER.md");

const md = readFileSync(SRC, "utf8");
mkdirSync(join(ROOT, "frontend", "src", "content"), { recursive: true });
writeFileSync(
  OUT,
  `// GENERATED by scripts/export-whitepaper.ts from docs/WHITEPAPER.md — do not edit by hand.\n` +
    `export const WHITEPAPER_MARKDOWN = ${JSON.stringify(md)};\n`,
);
// The download button on /whitepaper points at /WHITEPAPER.md; ship the same bytes as a static file.
writeFileSync(PUBLIC, md);
console.log(`exported ${md.length} chars → ${OUT} (+ public/WHITEPAPER.md)`);
